#!/usr/bin/env bash
# verify.sh - 型チェック・フォーマットテスト・固有名詞チェックを順番に実行してスコアを出力する
# 使い方: bash scripts/verify.sh

set -euo pipefail

SCORE=0
TOTAL=100

echo "======================================================"
echo "  椎葉村議会 議事録自動生成システム - 検証スクリプト"
echo "======================================================"
echo ""

# --------------------------------------------------
# 1. mypy で型チェック (20点)
# --------------------------------------------------
echo "------------------------------------------------------"
echo "[1/3] 型チェック (mypy src/) ... 最大20点"
echo "------------------------------------------------------"

if command -v mypy &>/dev/null; then
    if mypy src/ --ignore-missing-imports 2>&1; then
        echo "✓ 型チェック: PASS (+20点)"
        SCORE=$((SCORE + 20))
    else
        echo "✗ 型チェック: FAIL (+0点)"
    fi
else
    echo "⚠ mypy がインストールされていません。スキップします。(+0点)"
fi

echo ""

# --------------------------------------------------
# 2. pytest でフォーマットテスト (40点)
# --------------------------------------------------
echo "------------------------------------------------------"
echo "[2/3] フォーマットテスト (pytest tests/test_format.py) ... 最大40点"
echo "------------------------------------------------------"

if command -v pytest &>/dev/null; then
    if pytest tests/test_format.py -v 2>&1; then
        echo "✓ フォーマットテスト: PASS (+40点)"
        SCORE=$((SCORE + 40))
    else
        echo "✗ フォーマットテスト: FAIL (+0点)"
    fi
else
    echo "⚠ pytest がインストールされていません。スキップします。(+0点)"
fi

echo ""

# --------------------------------------------------
# 3. 固有名詞チェック (40点)
# --------------------------------------------------
echo "------------------------------------------------------"
echo "[3/3] 固有名詞チェック (pytest tests/test_proper_nouns.py) ... 最大40点"
echo "------------------------------------------------------"

if command -v pytest &>/dev/null; then
    if pytest tests/test_proper_nouns.py -v 2>&1; then
        echo "✓ 固有名詞チェック: PASS (+40点)"
        SCORE=$((SCORE + 40))
    else
        echo "✗ 固有名詞チェック: FAIL (+0点)"
    fi
else
    echo "⚠ pytest がインストールされていません。スキップします。(+0点)"
fi

echo ""
echo "======================================================"
echo "  SCORE: ${SCORE}/${TOTAL}"
echo "======================================================"
