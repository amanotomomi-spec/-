def add_paragraph(doc: Document, text: str, style: str = "Normal") -> None:
    """段落を追加する。
    - 〇で始まる発言行：発言者部分（〇…君）をMSゴシック、発言内容をMS明朝
    - （…）で始まる傍聴行：中央揃え
    """
    para = doc.add_paragraph(style=style)

    # 傍聴・括弧書き行は中央揃え
    if text.startswith("（"):
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        para.add_run(text)
        return

    # 発言行（〇または○で始まる）：発言者部分をMSゴシック
    # 例: 〇議長（岡村　正司君）　発言内容
    m = re.match(r"(〇[^（]*（[^）]*君）)(　.*)?$", text, re.DOTALL)
    if m:
        speaker_part = m.group(1)          # 例: 〇議長（岡村　正司君）
        content_part = m.group(2) or ""   # 例: 　日程第１…

        # 発言者部分：MSゴシック
        run_speaker = para.add_run(speaker_part)
        run_speaker.font.name = "ＭＳ ゴシック"
        run_speaker.font.size = Pt(10.5)

        # 発言内容部分：MS明朝（Normalスタイルのまま）
        if content_part:
            run_content = para.add_run(content_part)
            run_content.font.name = "ＭＳ 明朝"
            run_content.font.size = Pt(10.5)
        return

    # 継続行（行頭が全角スペース）：MS明朝
    if text.startswith("　") or not text:
        para.add_run(text)
        return

    # それ以外は通常テキスト
    para.add_run(text)


def is_agenda_heading(text: str) -> bool:
    """日程見出し行かどうか判定。"""
    return re.match(r"^日程第[ \d]+[　\t]", text) is not None


def is_audience_line(text: str) -> bool:
    """傍聴・起立行かどうか判定。"""
    return text.startswith("（")


def format_speech_lines(speaker: str, content: str) -> list[str]:
    """
    発言行を整形して返す。
    同一人物の発言内改行は行頭に全角スペース1つを追加する。
    """
    lines = content.split("\n")
    result = []
    first = True
    for line in lines:
        if first:
            result.append(f"{speaker}　{line}")
            first = False
        else:
            # 改行後の行頭に全角スペース
            if line.startswith("　"):
                result.append(line)
            else:
                result.append(f"　{line}")
    return result


